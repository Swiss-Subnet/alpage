// A new GuestOS is elected every week or two, and every one of them has to be
// named in config before a node can be declared to run it. Hand-copying hashes
// is the churn `alp guestos sync` removes: it derives the elected set from the
// dashboard's election proposals and writes it as a generated resources file.

// DefaultGuestosPath is the generated catalogue, beside resources.hcl and
// merged with it like any other resources/*.hcl.
const DefaultGuestosPath = ResourcesDir + "/guestos.hcl"

// guestosHeader marks the catalogue generated, matching docs/config.md's
// convention.
const guestosHeader = "# Generated by `alp guestos sync`. Do not edit by hand.\n" +
	"# The elected GuestOS versions the NNS currently accepts for deployment.\n\n"

// ElectedRelease is one GuestOS version the NNS has elected and not since
// unelected.
type ElectedRelease struct {
	VersionID  string
	Name       string
	ProposalID uint64
}

// FetchElectedReleases returns the currently elected GuestOS versions, newest
// election last.
//
// The elected set is replayed from the election proposals rather than read from
// blessed_replica_versions, which is not maintained (see ElectedVersions). The
// replay is sound despite the capped scan window: unelection always happens in
// a later proposal than the election it reverses, so a version whose election
// is in the window has its unelection in the window too. A version elected
// before the window is missing rather than wrong.
func FetchElectedReleases(dashboardBase string) ([]ElectedRelease, error) {
	body, err := fetchElections(dashboardBase)
	if err != nil {
		return nil, err
	}
	return parseElectedReleases(body)
}

func parseElectedReleases(body []byte) ([]ElectedRelease, error) {
	var d struct {
		Data []electionProposal `json:"data"`
	}
	if err := json.Unmarshal(body, &d); err != nil {
		return nil, fmt.Errorf("parse dashboard elections: %w", err)
	}
	// Ascending proposal id is chronological order, which the replay needs: the
	// dashboard serves newest first, and applying an unelection before the
	// election it reverses would leave the version elected.
	props := append([]electionProposal(nil), d.Data...)
	sort.Slice(props, func(i, j int) bool { return props[i].ID < props[j].ID })

	elected := map[string]ElectedRelease{}
	for _, p := range props {
		if v := p.Payload.ReplicaVersionToElect; v != "" {
			elected[v] = ElectedRelease{VersionID: v, Name: releaseName(p.Summary), ProposalID: p.ID}
		}
		for _, v := range p.Payload.ReplicaVersionsToUnelect {
			delete(elected, v)
		}
	}
	out := make([]ElectedRelease, 0, len(elected))
	for _, r := range elected {
		out = append(out, r)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ProposalID < out[j].ProposalID })
	return out, nil
}

// DefaultReleaseVariant is the release flavour `--set` picks. DFINITY elects
// several variants per release -- the base build plus feature builds -- so
// "newest elected" alone does not identify one version.
const DefaultReleaseVariant = "base"

// LatestRelease is the most recently elected release of the given variant.
func LatestRelease(rs []ElectedRelease, variant string) (ElectedRelease, error) {
	suffix := "-" + variant
	var best ElectedRelease
	for _, r := range rs {
		if strings.HasSuffix(r.Name, suffix) && r.ProposalID >= best.ProposalID {
			best = r
		}
	}
	if best.VersionID == "" {
		return ElectedRelease{}, fmt.Errorf("no elected release matches variant %q among %d elected versions", variant, len(rs))
	}
	return best, nil
}

// RenderGuestosHCL renders the elected set as guestos_version blocks.
func RenderGuestosHCL(rs []ElectedRelease) string {
	f := hclwrite.NewEmptyFile()
	body := f.Body()
	for i, r := range rs {
		if i > 0 {
			body.AppendNewline()
		}
		b := body.AppendNewBlock("guestos_version", []string{versionBlockLabel(r)})
		b.Body().SetAttributeValue("id", cty.StringVal(r.VersionID))
		if r.Name != "" {
			b.Body().SetAttributeValue("label", cty.StringVal(r.Name))
		}
	}
	return guestosHeader + string(f.Bytes())
}

// versionBlockLabel derives an HCL identifier from a release name, since a
// reference (guestos_version.<name>.id) cannot carry the hyphens and dots a
// release name has. An unnamed release falls back to its hash prefix.
func versionBlockLabel(r ElectedRelease) string {
	if r.Name == "" {
		n := len(r.VersionID)
		if n > 8 {
			n = 8
		}
		return "v_" + r.VersionID[:n]
	}
	return strings.Map(func(c rune) rune {
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', c == '_':
			return c
		default:
			return '_'
		}
	}, r.Name)
}

// WriteGuestosHCL writes the catalogue, creating its directory.
func WriteGuestosHCL(path string, rs []ElectedRelease) error {
	if dir := filepath.Dir(path); dir != "" {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, []byte(RenderGuestosHCL(rs)), 0o644)
}

// SetVersionAlias repoints a hand-written guestos_version block at rel,
// searching the resource files beside resourcesPath. Rewriting in place rather
// than regenerating keeps the block's comments and its default marker, and puts
// the new hash in the diff. Returns the file changed.
func SetVersionAlias(resourcesPath, alias string, rel ElectedRelease) (string, error) {
	files, err := resourceHCLPaths(resourcesPath)
	if err != nil {
		return "", err
	}
	for _, fp := range files {
		src, err := os.ReadFile(fp)
		if err != nil {
			return "", err
		}
		f, diags := hclwrite.ParseConfig(src, fp, hcl.InitialPos)
		if diags.HasErrors() {
			return "", fmt.Errorf("parse %s: %s", fp, diags.Error())
		}
		for _, b := range f.Body().Blocks() {
			if b.Type() != "guestos_version" || len(b.Labels()) != 1 || b.Labels()[0] != alias {
				continue
			}
			b.Body().SetAttributeValue("id", cty.StringVal(rel.VersionID))
			if rel.Name != "" {
				b.Body().SetAttributeValue("label", cty.StringVal(rel.Name))
			}
			if err := os.WriteFile(fp, f.Bytes(), 0o644); err != nil {
				return "", err
			}
			return fp, nil
		}
	}
	return "", fmt.Errorf("no guestos_version %q found beside %s; declare the alias block first", alias, resourcesPath)
}
