// Two releases elected, the older one unelected by the newer proposal. The
// dashboard serves newest first, which is the order the replay must not trust.
const electionReplayJSON = `{"data":[
  {"id":143165,"summary":"Release Notes for [release-2026-07-23\\_04-21-base](https://github.com/dfinity/ic/tree/y)","payload":{"replica_version_to_elect":"bbbb","replica_versions_to_unelect":["aaaa"]}},
  {"id":143078,"summary":"Release Notes for [release-2026-07-09\\_03-11-base](https://github.com/dfinity/ic/tree/x)","payload":{"replica_version_to_elect":"aaaa"}}
]}`

func TestParseElectedReleasesAppliesUnelections(t *testing.T) {
	got, err := parseElectedReleases([]byte(electionReplayJSON))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if len(got) != 1 {
		t.Fatalf("got %d elected, want 1: %+v", len(got), got)
	}
	if got[0].VersionID != "bbbb" {
		t.Errorf("elected = %q, want bbbb", got[0].VersionID)
	}
	if want := "release-2026-07-23_04-21-base"; got[0].Name != want {
		t.Errorf("name = %q, want %q", got[0].Name, want)
	}
}

// The unelection must be applied after the election it reverses, whatever order
// the feed arrives in: reversing the two would leave the version elected.
func TestParseElectedReleasesIgnoresFeedOrder(t *testing.T) {
	reordered := `{"data":[
	  {"id":143078,"summary":"Release Notes for [release-a](x)","payload":{"replica_version_to_elect":"aaaa"}},
	  {"id":143165,"summary":"Release Notes for [release-b](y)","payload":{"replica_version_to_elect":"bbbb","replica_versions_to_unelect":["aaaa"]}}
	]}`
	got, err := parseElectedReleases([]byte(reordered))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if len(got) != 1 || got[0].VersionID != "bbbb" {
		t.Errorf("got %+v, want only bbbb elected", got)
	}
}

func TestLatestReleasePicksVariant(t *testing.T) {
	rs := []ElectedRelease{
		{VersionID: "aaaa", Name: "release-2026-07-23_04-21-base", ProposalID: 100},
		{VersionID: "bbbb", Name: "release-2026-08-06_11-02-base", ProposalID: 200},
		// A later feature build must not win the base slot.
		{VersionID: "cccc", Name: "release-2026-08-06_11-02-hashes-in-blocks", ProposalID: 201},
	}
	got, err := LatestRelease(rs, DefaultReleaseVariant)
	if err != nil {
		t.Fatalf("latest: %v", err)
	}
	if got.VersionID != "bbbb" {
		t.Errorf("latest base = %q, want bbbb", got.VersionID)
	}
}

func TestLatestReleaseNoSuchVariant(t *testing.T) {
	rs := []ElectedRelease{{VersionID: "aaaa", Name: "release-x-base", ProposalID: 1}}
	if _, err := LatestRelease(rs, "nonesuch"); err == nil {
		t.Fatal("an unmatched variant must error rather than pick arbitrarily")
	}
}

// The generated catalogue must parse back as resources, with labels that are
// usable as references (a release name is not an HCL identifier).
func TestRenderGuestosHCLRoundTrips(t *testing.T) {
	rs := []ElectedRelease{
		{VersionID: "aaaa", Name: "release-2026-07-23_04-21-base", ProposalID: 100},
		{VersionID: "bbbb", ProposalID: 200},
	}
	src := RenderGuestosHCL(rs)
	if !strings.HasPrefix(src, "# Generated by") {
		t.Errorf("catalogue must be marked generated: %q", src)
	}
	path := writeResources(t, src)
	r, err := loadResources(path)
	if err != nil {
		t.Fatalf("generated catalogue does not parse: %v\n%s", err, src)
	}
	if len(r.Versions) != 2 {
		t.Fatalf("got %d versions, want 2", len(r.Versions))
	}
	if got := r.Versions[0].Name; got != "release_2026_07_23_04_21_base" {
		t.Errorf("label = %q, want an identifier-safe name", got)
	}
	if got := r.Versions[1].Name; got != "v_bbbb" {
		t.Errorf("unnamed release label = %q, want v_bbbb", got)
	}
}

func TestSetVersionAliasRewritesInPlace(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resources.hcl")
	const before = `guestos_version "current" {
  id      = "old"
  label   = "release-old"
  default = true
}
`
	if err := os.WriteFile(path, []byte(before), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := SetVersionAlias(path, "current", ElectedRelease{VersionID: "new", Name: "release-new"})
	if err != nil {
		t.Fatalf("set alias: %v", err)
	}
	if got != path {
		t.Errorf("edited %q, want %q", got, path)
	}
	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`id      = "new"`, `label   = "release-new"`, "default = true"} {
		if !strings.Contains(string(out), want) {
			t.Errorf("rewritten file missing %q:\n%s", want, out)
		}
	}
}

// The alias may live in any merged resource file, and a missing one must say so
// rather than silently writing nothing.
func TestSetVersionAliasFindsSplitFileAndReportsMissing(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resources.hcl")
	if err := os.WriteFile(path, []byte("subnet \"s\" {\n  id = \"aaaaa-aa\"\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, ResourcesDir), 0o755); err != nil {
		t.Fatal(err)
	}
	split := filepath.Join(dir, ResourcesDir, "versions.hcl")
	if err := os.WriteFile(split, []byte("guestos_version \"current\" {\n  id = \"old\"\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := SetVersionAlias(path, "current", ElectedRelease{VersionID: "new", Name: "release-new"})
	if err != nil {
		t.Fatalf("set alias: %v", err)
	}
	if got != split {
		t.Errorf("edited %q, want %q", got, split)
	}
	if _, err := SetVersionAlias(path, "absent", ElectedRelease{VersionID: "new"}); err == nil {
		t.Error("an undeclared alias must error")
	}
}
